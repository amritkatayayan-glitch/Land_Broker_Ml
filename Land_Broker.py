# Function to accept valid numerical input
def get_positive_float(message, allow_zero=False):
    while True:
        try:
            value = float(input(message))

            if not np.isfinite(value):
                print("Please enter a finite number.")
                continue

            if allow_zero and value >= 0:
                return value

            if not allow_zero and value > 0:
                return value

            print(
                "Please enter a value greater than or equal to zero."
                if allow_zero
                else "Please enter a value greater than zero."
            )

        except ValueError:
            print("Please enter a valid number.")


def get_yes_no(message):
    while True:
        answer = input(message).strip().lower()

        if answer in ["yes", "y", "1"]:
            return 1

        if answer in ["no", "n", "0"]:
            return 0

        print("Please enter Yes or No.")


# Get property details
